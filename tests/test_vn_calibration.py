"""Viet Nam calibration: synthetic series with KNOWN parameters (the fit must recover them), the discrete-time R mapping, the
no-data behaviour (NO_CALIBRATION, never a default presented as calibrated) and the sandbox overlay rules. No network."""
import math
from datetime import date, timedelta

import numpy as np
import pytest

from healthpulse.vietnam import calibration as cal
from healthpulse.vietnam import sandbox as sb

PAR = dict(N=98e6, latent=4.0, infectious=6.0, report=0.3, immune=0.2, cfr_hosp=0.12, admit_delay=6, los=9.0)


def _synthetic(Rd_knots, I0, p_hosp, los, ndays=210, noise=0.0, seed=1):
    """Weekly cases/deaths generated by the engine's own deterministic chain from a known R(t)."""
    Rd = cal._Rdaily(np.log(np.array(Rd_knots, float)), ndays)
    sim = cal._simulate(Rd, I0, PAR, ndays, p_hosp, los)
    d0 = date(2021, 5, 1)
    idx = np.arange(13, ndays, 7)
    ends = np.array([d0 + timedelta(days=int(i)) for i in idx])
    cases, deaths = cal._wk(sim["rep"], idx), cal._wk(sim["dead"], idx)
    if noise:
        rng = np.random.default_rng(seed)
        cases = rng.poisson(cases * (1 + noise * rng.standard_normal(len(cases))).clip(0.5)).astype(float)
        deaths = rng.poisson(deaths).astype(float)
    wv = dict(ends=ends, idx=idx, cases=cases.astype(float), deaths=deaths.astype(float), use_c=np.ones(len(idx), bool), use_d=idx > 28, ndays=ndays,
              day0=d0, spec={})
    return wv, Rd, sim


def test_discrete_chain_growth_matches_R():
    sg, gm = 1 / 5.5, 1 / 5.0
    for R in (0.7, 1.0, 1.4, 2.5):
        r = sb.R_to_growth(R, sg, gm)
        assert float(sb.growth_to_R(r, sg, gm)) == pytest.approx(R, rel=1e-9)
    # a huge population (no depletion) grown with the engine's chain reproduces the predicted rate
    par = dict(PAR, N=1e15, latent=5.5, infectious=5.0, immune=0.0)
    for R in (0.8, 1.6):
        sim = cal._simulate(np.full(300, R), 1e4, par, 300, 0.0, 5.0)
        r_emp = math.log(sim["rep"][250:280].sum() / sim["rep"][220:250].sum()) / 30
        assert r_emp == pytest.approx(sb.R_to_growth(R, 1 / 5.5, 1 / 5.0), abs=2e-4)


def test_case_fit_recovers_a_known_R_path():
    knots = [3.0, 2.4, 1.6, 0.8, 0.9, 1.5, 1.3, 1.1, 0.9, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8]
    wv, Rd, sim = _synthetic(knots, 800.0, 0.03, 9.0, noise=0.03)
    f = cal._fit_cases(wv, PAR, nfev=120)
    assert f["rmse_log"] < 0.12
    # the fitted path matches the generating one where the data constrain it (the mid-window days)
    ratio = f["Rd"][20:150] / Rd[20:150]
    assert np.median(np.abs(np.log(ratio))) < 0.2
    assert f["I0"] == pytest.approx(800.0, rel=0.8)


def test_death_fit_recovers_p_hosp_and_timing():
    knots = [2.5, 2.0, 1.5, 1.0, 0.8, 0.7] + [0.7] * 10
    # noise-free: exact recovery of both parameters
    wv, Rd, sim = _synthetic(knots, 2000.0, 0.035, 11.0)
    fit = cal._fit_deaths(wv, PAR, sim["inS"], free_los=True)
    assert fit["p_hosp"] == pytest.approx(0.035, rel=1e-3) and fit["los"] == pytest.approx(11.0, rel=1e-3)
    # noisy: the IDENTIFIED quantities (deaths per infection, mean infection-to-death delay) are recovered, the split is looser
    wv, Rd, sim = _synthetic(knots, 2000.0, 0.035, 11.0, noise=0.02)
    fit = cal._fit_deaths(wv, PAR, sim["inS"], free_los=True)
    got, true = cal._death_stats(PAR, fit["p_hosp"], fit["los"], sim["inS"], None), cal._death_stats(PAR, 0.035, 11.0, sim["inS"], None)
    assert got["deaths_per_infection"] == pytest.approx(true["deaths_per_infection"], rel=0.15)
    assert got["mean_infection_to_death_days"] == pytest.approx(true["mean_infection_to_death_days"], rel=0.35)
    # pinned: with the timing held at the preset the deaths-per-infection is still right
    pin = cal._fit_deaths(wv, PAR, sim["inS"], free_los=False, x0=fit["x"])
    st_pin = cal._death_stats(PAR, pin["p_hosp"], PAR["los"], sim["inS"], None)["deaths_per_infection"]
    assert st_pin == pytest.approx(true["deaths_per_infection"], rel=0.15)


def test_death_stats_match_the_simulation():
    wv, Rd, sim = _synthetic([2.0, 1.5, 1.0] + [0.5] * 20, 2000.0, 0.03, 9.0, ndays=400)  # the wave ends well before day 400
    st = cal._death_stats(PAR, 0.03, 9.0, sim["inS"], sim["rep"])
    assert st["deaths_per_infection"] == pytest.approx(sim["dead"].sum() / sim["inS"].sum(), rel=0.05)
    assert st["deaths_per_reported_case"] == pytest.approx(st["deaths_per_infection"] / PAR["report"])


def test_growth_rate_and_interval():
    ends = np.array([date(2022, 2, 13) + timedelta(days=7 * i) for i in range(6)])
    cases = 1e5 * np.exp(0.08 * 7 * np.arange(6)) * np.array([1.02, 0.98, 1.01, 0.99, 1.0, 1.0])
    wv = dict(ends=ends, cases=cases, spec=dict(growth=(date(2022, 2, 13), date(2022, 3, 13)), growth_label="x"))
    g = cal._growth(wv, dict(PAR), np.random.default_rng(0), B=300)
    assert g["r_per_day"] == pytest.approx(0.08, abs=0.01)
    assert g["r_ci90"][0] < g["r_per_day"] < g["r_ci90"][1]
    assert g["R_early"] == pytest.approx(float(sb.growth_to_R(g["r_per_day"], 1 / 4.0, 1 / 6.0)))


def test_flat_cost_surface_is_reported_not_hidden():
    """When the weekly series cannot tell two immune shares apart (same cost), the pinning must keep the ASSUMED value."""
    wv, Rd, sim = _synthetic([1.6, 1.6, 1.4, 1.0, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8, 0.8], 1500.0, 0.03, 9.0)
    pin = cal._pin_immune(wv, PAR, quick=True)
    # a small epidemic (a few % of the population) is feasible for every immune share, so the cost is flat and nothing moves
    assert pin["moved"] is False and pin["pinned"] == PAR["immune"]


