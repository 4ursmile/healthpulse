def _built():
    from healthpulse.vietnam import data
    if not data.is_built():
        pytest.skip("Viet Nam data not built (hp vn-fetch)")


def test_dengue_engine_follows_the_fitted_level():
    """Without the ensemble shock, the engine's annual total must match the model it is built on (this was off by ~3.5x before the
    discrete-time R fix)."""
    _built()
    from healthpulse.vietnam import model
    k = model.model_info()["kappa"]
    import polars as pl
    y = 2019
    est = model.estimates().filter(pl.col("month").dt.year() == y)["expected_raw"].sum() * k
    sim = cal.engine_year(y, trials=4, noshock=True).sum(0).mean()
    assert sim == pytest.approx(est, rel=0.15)


