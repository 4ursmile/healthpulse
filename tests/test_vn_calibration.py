def test_stale_overlay_is_flagged(tmp_path, monkeypatch):
    import json
    monkeypatch.setattr(sb, "gold_dir", lambda: tmp_path)
    (tmp_path / "calibration.json").write_text(json.dumps({"inputs": {"engine_sha256": "not-this-engine"},
                                                           "overlay": {"covid": {"params": {}, "note": "n", "status": "PARTIAL"}}}))
    assert sb.read_overlay()["covid"]["stale"] is True
    (tmp_path / "calibration.json").write_text(json.dumps({"inputs": {"engine_sha256": sb.engine_sha()}, "overlay": {"covid": {"params": {}}}}))
    assert sb.read_overlay()["covid"]["stale"] is False
    (tmp_path / "calibration.json").write_text("{ not json")
    assert sb.read_overlay() == {}  # unreadable artefact -> nothing is overlaid
